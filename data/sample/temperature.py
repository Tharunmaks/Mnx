def celsius_to_fahrenheit(c):
    """Convert degrees Celsius to Fahrenheit."""
    return c * 9 / 5 + 32


def fahrenheit_to_celsius(f):
    """Convert degrees Fahrenheit to Celsius."""
    return (f - 32) * 5 / 9


def celsius_to_kelvin(c):
    """Convert degrees Celsius to Kelvin."""
    return c + 273.15
